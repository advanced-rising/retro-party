/** 만들 수 있는 서로 다른 이름의 수. 테스트가 이 값이 만 개 이상임을 지킨다 */
export const NICKNAME_COMBINATIONS = MODIFIERS.length * SUBJECTS.length

export interface NicknameParts {
  readonly modifier: string
  readonly subject: string
}

/** 시드를 주면 재현 가능하게, 없으면 그냥 무작위로 */
export function makeNickname(rng?: Rng): string {
  const pick = <T>(xs: readonly T[]): T => {
    const i = rng === undefined ? Math.floor(Math.random() * xs.length) : rng.int(xs.length)
    return xs[i] as T
  }
  return trimName(`${pick(MODIFIERS)}${pick(SUBJECTS)}`)
}

/**
 * 코드포인트 단위로 자른다. 바이트로 자르면 한글이 반쪽 난다.
 * 비어 있으면 부르기 곤란하므로 최소한의 이름을 남긴다.
 */
export function trimName(raw: string): string {
  const chars = [...raw.trim()]
  if (chars.length === 0) return '이름없음'
  return chars.slice(0, MAX_NICKNAME).join('')
}

/** 전체 조합. 테스트와 도구가 같은 소스를 본다 */
export const NICKNAME_PARTS: readonly NicknameParts[] = MODIFIERS.flatMap((modifier) =>
  SUBJECTS.map((subject) => ({ modifier, subject })),
)
